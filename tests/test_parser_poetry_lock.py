"""``poetry.lock`` parser tests.

The fixture is a realistic lock file: resolved versions, dev groups, registry
and git sources, alternative constraints per Python version, breakage.  The
assertions follow one rule: every version that appears must come from the file,
and nothing may be invented.
"""

from __future__ import annotations

import pytest

from app.core.config import Settings
from app.ingestion.parsers import MappingFileResolver, ParserContext, parse_poetry_lock
from app.ingestion.parsers.base import ParseOutcome
from app.models.common import (
    ManifestParseStatus,
    Severity,
    SourceKind,
    WarningCode,
)
from tests.support import make_settings

POETRY_LOCK = """# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.
[[package]]
name = "requests"
version = "2.31.0"
description = "Python HTTP for Humans."
optional = false
python-versions = ">=3.7"
groups = ["main"]
files = [
    {file = "requests-2.31.0-py3-none-any.whl", hash = "sha256:aaaa"},
]

[package.dependencies]
certifi = ">=2017.4.17"
charset-normalizer = {version = ">=2,<4", markers = 'python_version >= "3"'}
pysocks = {version = "!=1.5.7,>=1.5.6", optional = true, extras = ["socks"], markers = 'extra == "socks"'}

[[package]]
name = "certifi"
version = "2024.2.2"
optional = false
python-versions = ">=3.6"
groups = ["main", "dev"]
files = []

[[package]]
name = "pytest"
version = "8.2.0"
optional = false
python-versions = ">=3.8"
groups = ["dev"]
files = []

[package.dependencies]
pluggy = "<2,>=1.5"
tomli = [
    {version = ">=1", markers = 'python_version < "3.11"'},
    {version = ">=2", markers = 'python_version >= "3.11"'},
]

[[package]]
name = "gitdep"
version = "1.0.0"
optional = false
python-versions = "*"
groups = ["main"]
files = []

[package.source]
type = "git"
url = "https://github.com/foo/bar.git"
reference = "v1.0"
resolved_reference = "0123456789abcdef0123456789abcdef01234567"

[metadata]
lock-version = "2.0"
python-versions = "^3.10"
content-hash = "abc123"
"""


def parse(text: str, *, settings: Settings | None = None) -> ParseOutcome:
    context = ParserContext(
        path="poetry.lock",
        text=text,
        settings=settings or make_settings(),
        resolver=MappingFileResolver({}),
    )
    return parse_poetry_lock(context)


def codes(outcome: ParseOutcome) -> set[str]:
    return {warning.code.value for warning in outcome.warnings}


def warning(outcome: ParseOutcome, code: WarningCode):
    matches = [w for w in outcome.warnings if w.code is code]
    assert matches, f"expected warning {code} in {sorted(codes(outcome))}"
    return matches[0]


def packages(outcome: ParseOutcome) -> dict[str, object]:
    return {package.normalized_name: package for package in outcome.resolved_packages}


def edges(outcome: ParseOutcome, *, to_name: str):
    return [edge for edge in outcome.edges if edge.to_name == to_name]


# ---------------------------------------------------------------------------
# Happy path
# ---------------------------------------------------------------------------
def test_resolved_packages_carry_versions_groups_and_sources() -> None:
    outcome = parse(POETRY_LOCK)
    assert outcome.status is ManifestParseStatus.PARSED
    assert outcome.requires_python == "^3.10"
    assert outcome.metadata["lock_version"] == "2.0"
    assert outcome.metadata["python_versions"] == "^3.10"
    assert outcome.metadata["content_hash"] == "abc123"
    assert outcome.metadata["file_counts"] == {"requests": 1, "certifi": 0, "pytest": 0, "gitdep": 0}

    by_name = packages(outcome)
    assert list(by_name) == ["requests", "certifi", "pytest", "gitdep"]

    requests = by_name["requests"]
    assert requests.version == "2.31.0"
    assert requests.groups == ("main",)
    assert requests.is_dev is False
    assert requests.is_optional is False
    assert requests.requires_python == ">=3.7"
    assert requests.source_kind is SourceKind.REGISTRY
    assert requests.source_reference is None
    assert requests.dependency_count == 3
    assert requests.source_manifest == "poetry.lock"

    # A package needed by main *and* dev is a runtime dependency.
    certifi = by_name["certifi"]
    assert certifi.groups == ("dev", "main")
    assert certifi.is_dev is False

    # Only a package absent from "main" is development-only.
    assert by_name["pytest"].is_dev is True
    assert by_name["pytest"].groups == ("dev",)

    gitdep = by_name["gitdep"]
    assert gitdep.source_kind is SourceKind.GIT
    assert gitdep.source_reference == "https://github.com/foo/bar.git"
    assert gitdep.requires_python is None  # "*" means "any", not "3.*"

    assert outcome.sections["packages"] == 4
    assert outcome.sections["dev_packages"] == 1


def test_line_numbers_point_at_the_package_headers() -> None:
    outcome = parse(POETRY_LOCK)
    lines = {package.normalized_name: package.provenance.line_number for package in outcome.resolved_packages}
    assert lines == {"requests": 2, "certifi": 18, "pytest": 26, "gitdep": 41}


def test_dependency_edges_are_extracted_with_markers_and_extras() -> None:
    outcome = parse(POETRY_LOCK)
    assert len(outcome.edges) == 6

    certifi_edge = edges(outcome, to_name="certifi")[0]
    assert certifi_edge.from_name == "requests"
    assert certifi_edge.from_version == "2.31.0"
    assert certifi_edge.to_version_constraint == ">=2017.4.17"
    assert certifi_edge.optional is False
    assert certifi_edge.provenance.section == "package.dependencies"

    charset = edges(outcome, to_name="charset-normalizer")[0]
    assert charset.to_version_constraint == ">=2,<4"
    assert charset.marker == 'python_version >= "3"'

    pysocks = edges(outcome, to_name="pysocks")[0]
    assert pysocks.optional is True
    assert pysocks.extras == ("socks",)
    assert pysocks.marker == 'extra == "socks"'

    pluggy = edges(outcome, to_name="pluggy")[0]
    assert pluggy.from_name == "pytest"
    assert pluggy.to_version_constraint == "<2,>=1.5"


def test_alternative_constraints_become_separate_edges() -> None:
    outcome = parse(POETRY_LOCK)
    tomli_edges = edges(outcome, to_name="tomli")
    assert {edge.to_version_constraint for edge in tomli_edges} == {">=1", ">=2"}
    assert {edge.marker for edge in tomli_edges} == {'python_version < "3.11"', 'python_version >= "3.11"'}
    assert len({edge.id for edge in tomli_edges}) == 2

    multiple = warning(outcome, WarningCode.MULTIPLE_CONSTRAINTS_FOR_PACKAGE)
    assert multiple.severity is Severity.INFO
    assert multiple.details["package"] == "tomli"
    assert multiple.details["dependency_of"] == "pytest"


