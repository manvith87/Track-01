def test_lock_v1_category_is_used_when_groups_are_absent() -> None:
    outcome = parse(
        "[[package]]\n"
        'name = "legacy"\n'
        'version = "0.1.0"\n'
        'category = "dev"\n'
        'python-versions = "*"\n'
    )
    package = outcome.resolved_packages[0]
    assert package.groups == ("dev",)
    assert package.is_dev is True


def test_package_without_groups_is_reported_and_not_assumed_dev() -> None:
    outcome = parse("[[package]]\n" 'name = "mystery"\n' 'version = "1.0.0"\n' 'python-versions = "*"\n')
    package = outcome.resolved_packages[0]
    assert package.is_dev is False
    assert package.groups == ()
    no_markers = warning(outcome, WarningCode.LOCKFILE_NO_DEV_MARKERS)
    assert no_markers.severity is Severity.INFO


def test_package_without_version_is_skipped_never_guessed() -> None:
    outcome = parse("[[package]]\n" 'name = "broken"\n' 'python-versions = "*"\n')
    assert outcome.resolved_packages == []
    assert outcome.status is ManifestParseStatus.PARTIAL
    malformed = warning(outcome, WarningCode.MALFORMED_ENTRY)
    assert malformed.details["package"] == "broken"
    assert WarningCode.NO_DEPENDENCIES_FOUND.value in codes(outcome)


def test_package_without_name_is_skipped() -> None:
    outcome = parse("[[package]]\n" 'version = "1.0.0"\n')
    assert outcome.resolved_packages == []
    assert outcome.status is ManifestParseStatus.PARTIAL
    assert WarningCode.MALFORMED_ENTRY.value in codes(outcome)


def test_lock_without_packages_is_partial() -> None:
    outcome = parse('[metadata]\nlock-version = "2.0"\n')
    assert outcome.resolved_packages == []
    assert outcome.status is ManifestParseStatus.PARTIAL
    assert WarningCode.NO_DEPENDENCIES_FOUND.value in codes(outcome)


def test_invalid_toml_fails_the_file_not_the_run() -> None:
    outcome = parse("[[package]\nname = broken\n")
    assert outcome.status is ManifestParseStatus.FAILED
    assert outcome.resolved_packages == []
    assert outcome.errors[0].code.value == "manifest_parse_error"
    assert outcome.errors[0].line_number is not None
    assert outcome.errors[0].manifest_path == "poetry.lock"


def test_non_array_package_key_fails_the_file() -> None:
    outcome = parse('package = "requests"\n')
    assert outcome.status is ManifestParseStatus.FAILED
    assert outcome.errors[0].code.value == "manifest_parse_error"


def test_non_table_package_entries_are_skipped() -> None:
    outcome = parse("package = [1]\n")
    assert outcome.status is ManifestParseStatus.PARTIAL
    assert WarningCode.MALFORMED_ENTRY.value in codes(outcome)
    assert WarningCode.NO_DEPENDENCIES_FOUND.value in codes(outcome)


def test_dependencies_that_are_not_a_table_are_reported() -> None:
    outcome = parse(
        "[[package]]\n"
        'name = "x"\n'
        'version = "1.0.0"\n'
        'dependencies = "requests"\n'
        'python-versions = "*"\n'
    )
    assert outcome.status is ManifestParseStatus.PARTIAL
    assert WarningCode.MALFORMED_ENTRY.value in codes(outcome)
    assert outcome.edges == []


def test_dependency_edges_with_unsupported_shapes_are_reported() -> None:
    outcome = parse(
        "[[package]]\n"
        'name = "x"\n'
        'version = "1.0.0"\n'
        'python-versions = "*"\n'
        "\n"
        "[package.dependencies]\n"
        "certifi = 3\n"
    )
    assert outcome.status is ManifestParseStatus.PARTIAL
    assert outcome.edges == []
    malformed = warning(outcome, WarningCode.MALFORMED_ENTRY)
    assert malformed.details["dependency"] == "certifi"


def test_unknown_source_type_is_recorded_as_unknown() -> None:
    outcome = parse(
        "[[package]]\n"
        'name = "x"\n'
        'version = "1.0.0"\n'
        'python-versions = "*"\n'
        "\n"
        "[package.source]\n"
        'type = "svn"\n'
        'url = "https://example.com/repo"\n'
    )
    package = outcome.resolved_packages[0]
    assert package.source_kind is SourceKind.UNKNOWN
    assert package.source_reference == "https://example.com/repo"


@pytest.mark.parametrize(
    ("source_type", "expected"),
    [
        ("file", SourceKind.PATH),
        ("directory", SourceKind.PATH),
        ("url", SourceKind.URL),
        ("legacy", SourceKind.REGISTRY),
    ],
)
def test_source_types_map_to_source_kinds(source_type: str, expected: SourceKind) -> None:
    outcome = parse(
        "[[package]]\n"
        'name = "x"\n'
        'version = "1.0.0"\n'
        'python-versions = "*"\n'
        "\n"
        "[package.source]\n"
        f'type = "{source_type}"\n'
        'url = "https://example.com/thing"\n'
    )
    assert outcome.resolved_packages[0].source_kind is expected
